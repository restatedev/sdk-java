package my.restate.sdk.examples;

import dev.restate.common.Slice;
import dev.restate.sdk.endpoint.Endpoint;
import dev.restate.sdk.http.vertx.RestateHttpServer;
import dev.restate.serde.PayloadCodec;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.SecureRandom;
import java.util.Arrays;
import java.util.Objects;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CompletionException;
import javax.crypto.Cipher;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.SecretKeySpec;
import software.amazon.awssdk.core.SdkBytes;
import software.amazon.awssdk.services.kms.KmsAsyncClient;
import software.amazon.awssdk.services.kms.model.DataKeySpec;

public class EncryptedExample {

  /**
   * {@link PayloadCodec} is the interface to implement to encrypt/decrypt payloads.
   *
   * <p>The following example encrypts the payloads with AES-GCM-256, using envelope encryption:
   * each payload is encrypted with a new data encryption key (DEK) generated by AWS KMS, and stored
   * together with the DEK encrypted by KMS:
   *
   * <pre>
   * +--------+-------------------+---------------------+------------+------------------------------+
   * | RTv1\0 | DEK length        | Encrypted DEK (KMS) | IV         | Encrypted payload + auth tag |
   * |        | (u16, big endian) |                     | (12 bytes) | (AES-GCM-256)                |
   * +--------+-------------------+---------------------+------------+------------------------------+
   * </pre>
   *
   * <p>This invokes KMS for every encoded and decoded payload. To reduce the KMS usage, you can
   * reuse the same DEK for several payloads, and cache the decrypted DEKs.
   */
  public static final class KmsPayloadCodec implements PayloadCodec {

    private static final byte[] PREFIX = "RTv1\0".getBytes(StandardCharsets.US_ASCII);
    private static final int IV_LENGTH = 12;
    private static final int AUTH_TAG_LENGTH_BITS = 128;
    private static final SecureRandom RANDOM = new SecureRandom();

    private final KmsAsyncClient kms;
    private final String kmsKeyId;

    public KmsPayloadCodec(KmsAsyncClient kms, String kmsKeyId) {
      this.kms = kms;
      this.kmsKeyId = kmsKeyId;
    }

    @Override
    public CompletableFuture<Slice> encode(Slice payload) {
      byte[] plainText = payload.toByteArray();
      return kms.generateDataKey(req -> req.keyId(kmsKeyId).keySpec(DataKeySpec.AES_256))
          .thenApply(
              dataKey -> {
                byte[] encryptedDek = dataKey.ciphertextBlob().asByteArray();
                if (encryptedDek.length > 0xFFFF) {
                  throw new IllegalStateException("Encrypted DEK too long");
                }
                byte[] iv = new byte[IV_LENGTH];
                RANDOM.nextBytes(iv);
                byte[] cipherText =
                    aesGcm(Cipher.ENCRYPT_MODE, dataKey.plaintext().asByteArray(), iv, plainText);

                return Slice.wrap(
                    ByteBuffer.allocate(
                            PREFIX.length + 2 + encryptedDek.length + IV_LENGTH + cipherText.length)
                        .put(PREFIX)
                        .putShort((short) encryptedDek.length)
                        .put(encryptedDek)
                        .put(iv)
                        .put(cipherText)
                        .array());
              });
    }

    @Override
    public CompletableFuture<Slice> decode(Slice payload) {
      byte[] encryptedDek;
      byte[] iv;
      byte[] cipherText;
      try {
        byte[] data = payload.toByteArray();
        if (data.length < PREFIX.length
            || !Arrays.equals(data, 0, PREFIX.length, PREFIX, 0, PREFIX.length)) {
          throw new IllegalArgumentException("Invalid encrypted payload prefix");
        }
        ByteBuffer buffer = ByteBuffer.wrap(data, PREFIX.length, data.length - PREFIX.length);
        encryptedDek = new byte[Short.toUnsignedInt(buffer.getShort())];
        buffer.get(encryptedDek);
        iv = new byte[IV_LENGTH];
        buffer.get(iv);
        cipherText = new byte[buffer.remaining()];
        buffer.get(cipherText);
      } catch (Exception e) {
        return CompletableFuture.failedFuture(e);
      }

      return kms.decrypt(req -> req.ciphertextBlob(SdkBytes.fromByteArray(encryptedDek)))
          .thenApply(
              dek ->
                  Slice.wrap(
                      aesGcm(Cipher.DECRYPT_MODE, dek.plaintext().asByteArray(), iv, cipherText)));
    }

    /**
     * Every payload is encrypted with a new DEK and a random IV, so encoding the same payload twice
     * produces different bytes.
     */
    @Override
    public boolean isEncodingDeterministic() {
      return false;
    }

    private static byte[] aesGcm(int mode, byte[] dek, byte[] iv, byte[] input) {
      try {
        Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
        cipher.init(
            mode, new SecretKeySpec(dek, "AES"), new GCMParameterSpec(AUTH_TAG_LENGTH_BITS, iv));
        return cipher.doFinal(input);
      } catch (GeneralSecurityException e) {
        throw new CompletionException(e);
      } finally {
        Arrays.fill(dek, (byte) 0);
      }
    }
  }

  /**
   * Set the {@code KMS_KEY_ID} environment variable to the id of the KMS key to use. The AWS region
   * and credentials are resolved by the AWS SDK default providers, e.g. from the {@code AWS_REGION}
   * and {@code AWS_PROFILE} environment variables.
   */
  public static void main(String[] args) {
    // Initialize KmsPayloadCodec
    String kmsKeyId = Objects.requireNonNull(System.getenv("KMS_KEY_ID"));
    KmsAsyncClient kms = KmsAsyncClient.create();
    KmsPayloadCodec payloadCodec = new KmsPayloadCodec(kms, kmsKeyId);

    // Initialize endpoint with payload codec, then start listening. The codec will be used for all
    // registered services in this endpoint.
    var endpoint = Endpoint.bind(new Greeter()).withPayloadCodec(payloadCodec);
    RestateHttpServer.listen(endpoint);

    // Example client usage
    // * Create client with codec
    // Client client = Client.connect("http://localhost:8080", null, payloadCodec, null);
    // * Do request as usual
    // GreetingResponse response = client.service(EncryptedGreeter.class).greet(new
    // Greeting("Confidential"));
  }
}
